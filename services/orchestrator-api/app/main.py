@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    """Startup/shutdown hook: build expensive objects ONCE, not per request.

    Before the server accepts requests:
      1. open the read-only pool, reflect the schema, compile the DB agent (app.state.db_agent)
      2. open the chat pool, create the chat tables if needed, and mark replies left
         'pending' by a crash or restart as errors (app.state.chat_store)
      3. open the document pool and create the document tables (app.state.document_store)
      4. load the document models ONCE (embedder, reranker, tokenizer, Docling converter; plan
         gotcha 6), build the Doc agent
      5. build the input guard (plan 04: NeMo Guardrails, its own Groq models) and the orchestrator
         (plan 03): the agents as tools (the web agent searches DuckDuckGo through its MCP server; the email
         agent is the separate email service, reached over A2A, plan 05), the
         Postgres checkpointer for paused email approvals, minus checkpoints nobody can approve any
         more (app.state.orchestrator)
      6. recover interrupted documents and start the ingestion worker
    Tracing (Langfuse) is set up first, so everything after it can be traced; it's off without the Langfuse keys.
    After the server stops: stop the worker first, then close all pools, then send the last traces.

    AsyncExitStack closes whatever was opened, in reverse order, even if a later step
    fails (e.g. the chat pool can't connect after the read-only pool already opened).
    If Postgres is down or .env is wrong, the server fails to start with a clear error.
    """
    settings = get_settings()
    async with AsyncExitStack() as stack:
        tracing = setup_tracing(settings)
        stack.push_async_callback(asyncio.to_thread, tracing.shutdown)  # registered first -> runs LAST: final flush
        db = await stack.enter_async_context(ReadOnlyDatabase(settings.readonly_database_url))
        app.state.db_agent = DBAgent(db, await load_schema(db))
        logger.info("DB agent ready")

        chat_store = await stack.enter_async_context(ChatStore(settings.app_database_url))
        await chat_store.setup()
        interrupted = await chat_store.fail_stale_pending()
        app.state.chat_store = chat_store
        logger.info("Chat store ready (%d interrupted replies marked as error)", interrupted)

        # After the chat store: documents reference chat_sessions (a document belongs to one chat).
        document_store = await stack.enter_async_context(DocumentStore(settings.app_database_url))
        await document_store.setup()
        app.state.document_store = document_store
        logger.info("Document store ready")

        # Model loading is CPU work and may download files on first start: in a thread.
        embedder = await asyncio.to_thread(Embedder, settings.rag_embedding_model, settings.data_dir / "models")
        counter = await asyncio.to_thread(TokenCounter, settings.rag_embedding_model)
        app.state.embedder = embedder
        logger.info("Embedding model ready (%s)", embedder.model_name)

        reranker = (
            await asyncio.to_thread(Reranker, settings.rag_rerank_model, settings.data_dir / "models")
            if settings.rag_rerank
            else None
        )
        retriever = Retriever(document_store, embedder, reranker, settings.rag_candidates)
        app.state.doc_agent = DocAgent(
            document_store, retriever, settings.rag_top_k, settings.rag_context_tokens, settings.rag_min_rerank_score
        )
        logger.info("Doc agent ready (rerank: %s)", reranker.model_name if reranker else "off")

        # The web agent's tool lives in another process: the DuckDuckGo MCP server, started once with uvx (plan 04).
        # If it can't start, the app still starts and the orchestrator simply doesn't offer search_web.
        web_mcp = WebSearchMCP(settings)
        await web_mcp.start()
        stack.push_async_callback(web_mcp.close)  # stops the server process on shutdown
        web_agent = WebSearchAgent(
            web_mcp, max_results=settings.web_max_results, snippet_chars=settings.web_snippet_chars
        )

        # The email agent is another service too (services/email-a2a-service, CrewAI), reached over A2A (plan 05).
        # If it isn't reachable now, the app still starts and the orchestrator doesn't offer draft_email.
        email_agent = A2AEmailAgent.from_settings(settings)
        await email_agent.start()
        stack.push_async_callback(email_agent.close)

        # The orchestrator calls the agents above as tools.
        tools = AgentTools(
            app.state.db_agent,
            app.state.doc_agent,
            web_agent,
            email_agent,
            document_store,
            Limits.from_settings(settings),
        )
        checkpoints = await stack.enter_async_context(CheckpointStore(settings.app_database_url))
        await checkpoints.setup()
        orphans = await checkpoints.delete_orphans(await chat_store.awaiting_approval_message_ids())
        app.state.orchestrator = Orchestrator(tools, checkpoints.saver)
        app.state.input_guard = InputGuard.from_settings(settings)  # warns loudly if GUARD_ENABLED=false
        logger.info(
            "Orchestrator ready (%s; %d stale checkpoint threads deleted)", settings.groq_orchestrator_model, orphans
        )

        worker = IngestionWorker(
            document_store,
            partial(ingest_document, deps=_ingest_deps(document_store, embedder, counter)),
            settings.data_dir,
        )
        await worker.recover()
        worker.start()
        stack.push_async_callback(worker.stop)  # registered after the pools -> runs BEFORE they close
        logger.info("Ingestion worker started")

        app.state.readiness_checks = _readiness_checks(db, chat_store, worker, web_mcp, email_agent, settings)
        # Per-client limits on questions and uploads (app/ratelimit.py); None = off (RATE_LIMIT_ENABLED=false).
        app.state.rate_limiter = RateLimiter.from_settings(settings) if settings.rate_limit_enabled else None
        if app.state.rate_limiter is None:
            logger.warning("RATE_LIMIT_ENABLED=false: requests are not rate limited")

        yield


def _readiness_checks(
    db: ReadOnlyDatabase,
    chat_store: ChatStore,
    worker: IngestionWorker,
    web_mcp: WebSearchMCP,
    email_agent: A2AEmailAgent,
    settings: Settings,
) -> list[Check]:
    """What GET /api/health/ready probes. Required: the two database roles (no question works without them)."""

    async def database_readonly() -> str:
        """The DB agent's read-only pool answers."""
        await db.fetch_trusted("SELECT 1")
        return "readonly_agent"

    async def database_app() -> str:
        """The chats/documents/checkpoints pool answers."""
        await chat_store.fetch_one("SELECT 1")
        return "app_rw"

    async def ingestion_worker() -> str:
        """The document queue's worker loop is alive."""
        if not worker.running:
            raise RuntimeError("the worker loop is not running: uploaded documents won't be processed")
        return "running"

    async def web_search() -> str:
        """The DuckDuckGo MCP server's session is open (search_web is offered only then)."""
        if not web_mcp.available:
            raise RuntimeError("the DuckDuckGo MCP server is not running: search_web is not offered")
        return "DuckDuckGo MCP server"

    async def email_service() -> str:
        """The email service answers (and draft_email comes back if it was down)."""
        if not settings.email_agent_api_key.get_secret_value():
            raise Off("EMAIL_AGENT_API_KEY is not set: draft_email is not offered")
        return await email_agent.check()

    async def tracing() -> str:
        """Langfuse accepts our keys (auth_check is a blocking HTTP call: in a thread)."""
        client = get_tracing().client
        if client is None:
            raise Off("no Langfuse keys")
        if not await asyncio.to_thread(client.auth_check):
            raise RuntimeError("Langfuse rejected the keys")
        return settings.langfuse_base_url

    async def input_guard() -> str:
        """The input guard is on (its checks call Groq, so they are not probed here)."""
        if not settings.guard_enabled:
            raise Off("GUARD_ENABLED=false: messages are NOT checked")
        return "NeMo Guardrails input rails"

    return [
        Check("database (read-only, DB agent)", True, database_readonly),
        Check("database (chats, documents)", True, database_app),
        Check("ingestion worker", False, ingestion_worker),
        Check("web search", False, web_search),
        Check("email service", False, email_service),
        Check("tracing (Langfuse)", False, tracing),
        Check("input guard", False, input_guard),
    ]


def _ingest_deps(store: DocumentStore, embedder: Embedder, counter: TokenCounter) -> IngestDeps:
    """Wire the real parser, vision model, embedder and settings into the ingestion pipeline."""
    settings = get_settings()
    converter = build_converter()  # Docling loads its models on the first document
    vision_llm = get_llm("vision", max_tokens=VISION_MAX_TOKENS)

    def parse(path: Path, pictures_dir: Path, fallback_title: str) -> ParsedDocument:
        """Docling with the shared converter."""
        return parse_document(path, pictures_dir, converter, fallback_title)

    return IngestDeps(
        store=store,
        data_dir=settings.data_dir,
        parse=parse,
        describe=partial(describe_picture, llm=vision_llm),
        embedder=embedder,
        counter=counter,
        chunk_tokens=settings.rag_chunk_tokens,
        max_pages=settings.rag_max_pages,
        max_pictures=settings.rag_max_pictures_per_doc,
        min_picture_area=settings.rag_min_picture_area,
    )


app = FastAPI(title="Multi-Agent Ops Platform API", version="0.1.0", lifespan=lifespan)
app.include_router(chat_router)  # /api/chat and /api/sessions/... (app/chat/routes.py)
app.include_router(documents_router)  # /api/documents/... (app/documents/routes.py)


class AskRequest(BaseModel):
    """Body of POST /api/db/ask. FastAPI validates it and returns 422 if it's invalid."""

    question: str = Field(min_length=1, max_length=1_000, description="A question about the business data.")


@app.get("/api/health")
async def health() -> dict[str, str]:
    """Liveness check: the process is up (says nothing about its dependencies; see /api/health/ready)."""
    return {"status": "ok"}


@app.get("/api/health/ready")
async def ready(response: Response) -> dict:
    """Readiness: every dependency probed now. 200 when ready or degraded, 503 when a required part is down."""
    status, checks = await readiness(getattr(app.state, "readiness_checks", []))
    if status == "not_ready":
        response.status_code = 503
    return {"status": status, "checks": checks}


@app.post("/api/db/ask", dependencies=[Depends(rate_limit("questions"))])
async def ask_db(body: AskRequest, guard: InputGuardDep, agent: DBAgentDep) -> DBAgentResult:
    """Run the DB agent on one question, with no chat and no memory (for the CLI, debugging and evals).

    The input guard checks the question first (plan 04: nothing reaches an agent unchecked): a blocked
    question gets 400 with the refusal as `detail`, and the DB agent never sees it.
    Returns the answer, SQL, rows and workflow steps; nothing is saved. The agent already
    turns bad SQL and database errors into a normal answer (via its retry loop). Anything
    else, e.g. Groq unreachable after all retries, becomes a 502 and is logged in full.
    """
    question = body.question.strip()
    with get_tracing().trace("db ask", input=question, tags=["api"]) as trace:
        verdict = await guard.check(question)
        if verdict.status == "blocked":
            trace.update(output=verdict.answer, metadata={"blocked_by": "input guard"})
            raise HTTPException(status_code=400, detail=verdict.answer)
        try:
            result = await agent.ask(question, callbacks=get_tracing().callbacks())
        except Exception as error:
            logger.exception("DB agent failed for question: %s", body.question)
            trace.update(level="ERROR", status_message=f"{type(error).__name__}: {error}"[:200])
            raise HTTPException(status_code=502, detail=f"The agent failed: {type(error).__name__}: {error}") from error
        trace.update(output=result.answer, metadata={"success": result.success, "attempts": result.attempts})
        return result
