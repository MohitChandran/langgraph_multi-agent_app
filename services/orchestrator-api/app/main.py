# Uvicorn only configures its own loggers; without this, messages from our app.* modules are dropped.
logging.basicConfig(level=logging.INFO, format="%(levelname)s:     %(name)s - %(message)s")
logger = logging.getLogger(__name__)


@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    """Startup/shutdown hook: build expensive objects ONCE, not per request.

    Before the server accepts requests:
      1. open the read-only pool, reflect the schema, compile the DB agent (app.state.db_agent)
      2. open the chat pool, create the chat tables if needed, and mark replies left
         'pending' by a crash or restart as errors (app.state.chat_store)
      3. open the document pool and create the document tables (app.state.document_store)
      4. load the document models ONCE (embedder, tokenizer, Docling converter; plan gotcha 6),
         recover documents interrupted by a crash, and start the ingestion worker
    After the server stops: stop the worker first, then close all pools.

    AsyncExitStack closes whatever was opened, in reverse order, even if a later step
    fails (e.g. the chat pool can't connect after the read-only pool already opened).
    If Postgres is down or .env is wrong, the server fails to start with a clear error.
    """
    settings = get_settings()
    async with AsyncExitStack() as stack:
        db = await stack.enter_async_context(ReadOnlyDatabase(settings.readonly_database_url))
        app.state.db_agent = DBAgent(db, await load_schema(db))
        logger.info("DB agent ready")

        chat_store = await stack.enter_async_context(ChatStore(settings.app_database_url))
        await chat_store.setup()
        interrupted = await chat_store.fail_stale_pending()
        app.state.chat_store = chat_store
        logger.info("Chat store ready (%d interrupted replies marked as error)", interrupted)

        # After the chat store: documents reference chat_sessions (a document belongs to one chat).
        document_store = await stack.enter_async_context(DocumentStore(settings.app_database_url))
        await document_store.setup()
        app.state.document_store = document_store
        logger.info("Document store ready")

        # Model loading is CPU work and may download files on first start: in a thread.
        embedder = await asyncio.to_thread(Embedder, settings.rag_embedding_model, settings.data_dir / "models")
        counter = await asyncio.to_thread(TokenCounter, settings.rag_embedding_model)
        app.state.embedder = embedder
        logger.info("Embedding model ready (%s)", embedder.model_name)

        worker = IngestionWorker(
            document_store,
            partial(ingest_document, deps=_ingest_deps(document_store, embedder, counter)),
            settings.data_dir,
        )
        await worker.recover()
        worker.start()
        stack.push_async_callback(worker.stop)  # registered after the pools -> runs BEFORE they close
        logger.info("Ingestion worker started")

        yield


def _ingest_deps(store: DocumentStore, embedder: Embedder, counter: TokenCounter) -> IngestDeps:
    """Wire the real parser, vision model, embedder and settings into the ingestion pipeline."""
    settings = get_settings()
    converter = build_converter()  # Docling loads its models on the first document
    vision_llm = get_llm("vision", max_tokens=VISION_MAX_TOKENS)

    def parse(path: Path, pictures_dir: Path, fallback_title: str) -> ParsedDocument:
        """Docling with the shared converter."""
        return parse_document(path, pictures_dir, converter, fallback_title)

    return IngestDeps(
        store=store,
        data_dir=settings.data_dir,
        parse=parse,
        describe=partial(describe_picture, llm=vision_llm),
        embedder=embedder,
        counter=counter,
        chunk_tokens=settings.rag_chunk_tokens,
        max_pages=settings.rag_max_pages,
        max_pictures=settings.rag_max_pictures_per_doc,
        min_picture_area=settings.rag_min_picture_area,
    )


app = FastAPI(title="Multi-Agent Ops Platform API", version="0.1.0", lifespan=lifespan)
app.include_router(chat_router)  # /api/chat and /api/sessions/... (app/chat/routes.py)
app.include_router(documents_router)  # /api/documents/... (app/documents/routes.py)


class AskRequest(BaseModel):
    """Body of POST /api/db/ask. FastAPI validates it and returns 422 if it's invalid."""

    question: str = Field(min_length=1, max_length=1_000, description="A question about the business data.")


@app.get("/api/health")
async def health() -> dict[str, str]:
    """Liveness check: lets the UI (or Docker later) see that the API is up."""
    return {"status": "ok"}


@app.post("/api/db/ask")
async def ask_db(body: AskRequest, agent: DBAgentDep) -> DBAgentResult:
    """Run the DB agent on one question, with no chat and no memory (for the CLI, debugging and evals).

    Returns the answer, SQL, rows and workflow steps; nothing is saved. The agent already
    turns bad SQL and database errors into a normal answer (via its retry loop). Anything
    else, e.g. Groq unreachable after all retries, becomes a 502 and is logged in full.
    """
    try:
        return await agent.ask(body.question.strip())
    except Exception as error:
        logger.exception("DB agent failed for question: %s", body.question)
        raise HTTPException(status_code=502, detail=f"The agent failed: {type(error).__name__}: {error}") from error
