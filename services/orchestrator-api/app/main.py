"""FastAPI entrypoint: exposes the agents over HTTP so a browser UI can use them.

For now there is one real endpoint, POST /api/db/ask, which runs the DB agent directly.
In Phase 2 this grows into the gateway for the LangGraph orchestrator (streaming,
sessions, file uploads, HITL resume).

Run it (from services/orchestrator-api):
    uv run uvicorn app.main:app --reload --port 8000
Interactive API docs (generated by FastAPI from the code): http://localhost:8000/docs
"""

import logging
from collections.abc import AsyncIterator
from contextlib import AsyncExitStack, asynccontextmanager

from fastapi import FastAPI, HTTPException, Request
from pydantic import BaseModel, Field

from app.agents.db.database import ReadOnlyDatabase
from app.agents.db.graph import DBAgent
from app.agents.db.models import DBAgentResult
from app.agents.db.schema import load_schema
from app.chat.store import ChatStore
from app.config import get_settings

# Uvicorn only configures its own loggers; without this, messages from our app.* modules are dropped.
logging.basicConfig(level=logging.INFO, format="%(levelname)s:     %(name)s - %(message)s")
logger = logging.getLogger(__name__)


@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    """Startup/shutdown hook: build expensive objects ONCE, not per request.

    Before the server accepts requests:
      1. open the read-only pool, reflect the schema, compile the DB agent (app.state.db_agent)
      2. open the chat pool, create the chat tables if needed, and mark replies left
         'pending' by a crash or restart as errors (app.state.chat_store)
    After the server stops: close both pools.

    AsyncExitStack closes whatever was opened, in reverse order, even if a later step
    fails (e.g. the chat pool can't connect after the read-only pool already opened).
    If Postgres is down or .env is wrong, the server fails to start with a clear error.
    """
    settings = get_settings()
    async with AsyncExitStack() as stack:
        db = await stack.enter_async_context(ReadOnlyDatabase(settings.readonly_database_url))
        app.state.db_agent = DBAgent(db, await load_schema(db))
        logger.info("DB agent ready")

        chat_store = await stack.enter_async_context(ChatStore(settings.app_database_url))
        await chat_store.setup()
        interrupted = await chat_store.fail_stale_pending()
        app.state.chat_store = chat_store
        logger.info("Chat store ready (%d interrupted replies marked as error)", interrupted)

        yield


app = FastAPI(title="Multi-Agent Ops Platform API", version="0.1.0", lifespan=lifespan)


class AskRequest(BaseModel):
    """Body of POST /api/db/ask. FastAPI validates it and returns 422 if it's invalid."""

    question: str = Field(min_length=1, max_length=1_000, description="A question about the business data.")


@app.get("/api/health")
async def health() -> dict[str, str]:
    """Liveness check: lets the UI (or Docker later) see that the API is up."""
    return {"status": "ok"}


@app.post("/api/db/ask")
async def ask_db(body: AskRequest, request: Request) -> DBAgentResult:
    """Run the DB agent on one question and return the answer, SQL, rows and workflow steps.

    The agent already turns bad SQL and database errors into a normal answer (via its
    retry loop). Anything else, e.g. Groq being unreachable or rate-limited after all
    retries, becomes a 502 with a short message the UI can show, and is logged in full.
    """
    agent: DBAgent = request.app.state.db_agent
    try:
        return await agent.ask(body.question.strip())
    except Exception as error:
        logger.exception("DB agent failed for question: %s", body.question)
        raise HTTPException(status_code=502, detail=f"The agent failed: {type(error).__name__}: {error}") from error
